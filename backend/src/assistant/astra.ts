import { env } from "../env";
import type { AstraHealthContext } from "./context";
import type { AnalysisResult } from "./analyzer";

/**
 * Port of the standalone chatbot's app/assistant.py (ASTRA_Health_Chatbot).
 * The AI provider is unchanged: Google Gemini, model gemini-3.5-flash-lite,
 * temperature 0.3 — exactly as the user built it. The system prompt and the
 * per-message assembly below are preserved verbatim from that codebase; only
 * the data source moved from the local CSV to the user's real database rows
 * and multi-turn conversation history was added.
 *
 * Credentials: GEMINI_API_KEY comes from backend/.env (gitignored) and is
 * never sent to the browser.
 */

export const SYSTEM_PROMPT = `
You are ASTRA, an intelligent AI health assistant
designed specifically for astronauts during space missions.

Your responsibilities:

1. Answer general health questions.
2. Explain health information simply.
3. Analyze astronaut health indicators using provided data.
4. Explain findings generated by the health analyzer.
5. Connect symptoms reported by astronauts with their
   available health measurements, without assuming causation.
6. Provide scientifically responsible health guidance.

IMPORTANT RULES:

- Always use the provided health data when answering
  astronaut-specific health questions.
- Never invent medical measurements.
- Never assume missing data.
- Never diagnose diseases.
- Never claim that an astronaut is healthy just because
  no alert was triggered.
- Clearly distinguish measured values from possible explanations.
- If abnormal indicators or concerning symptoms exist,
  recommend contacting the mission medical officer.
- For severe or emergency symptoms, recommend immediate
  medical assistance.

Consider microgravity, radiation, isolation,
and limited medical resources.

Always be friendly, professional, and clear.

If health data is unavailable, tell the astronaut.
Do not make up health information.
`;

/** Verbatim structure of assistant.py's full_message, with real DB data. */
export function buildUserPrompt(
  ctx: AstraHealthContext | null,
  analysis: AnalysisResult | null,
  message: string,
): string {
  const healthContext = ctx
    ? JSON.stringify(ctx, null, 4)
    : "No health data available for this astronaut.";
  const analyzerResult = analysis
    ? JSON.stringify(analysis, null, 4)
    : "Health analysis unavailable.";
  return `
ASTRONAUT ID:
${ctx ? ctx.astronaut_id : "unknown"}

LATEST HEALTH MEASUREMENTS:
${healthContext}

HEALTH ANALYZER FINDINGS:
${analyzerResult}

ASTRONAUT QUESTION:
${message}

INSTRUCTIONS:

Answer the astronaut's question using the actual health
measurements and analyzer findings provided above.

Explain relevant measurements in simple language.

If the question is unrelated to personal health,
answer it normally.

Do not invent measurements or medical conclusions.
`;
}

export interface GeminiTurn {
  role: "user" | "model";
  text: string;
}

export interface AstraReply {
  text: string;
  /** Present when the user saw a fallback instead of a Gemini answer. */
  degraded: string | null;
}

export const FALLBACK_TEXT = "Sorry, ASTRA is temporarily unavailable.";

/** Gemini answers use markdown; chat bubbles render plain text — tidy it. */
export function presentReply(raw: string): string {
  return raw
    .replace(/\*\*(.+?)\*\*/g, "$1")
    .replace(/\*(.+?)\*/g, "$1")
    .replace(/^#{1,6}\s+/gm, "")
    .replace(/^\s*[-*]\s+/gm, "• ")
    .trim();
}

export async function askAstra(
  turns: GeminiTurn[],
  userContent: string,
): Promise<AstraReply> {
  if (!env.GEMINI_API_KEY) {
    // Same visible behaviour as the original when no key is configured,
    // but honest about why.
    return { text: FALLBACK_TEXT, degraded: "AI_NOT_CONFIGURED" };
  }
  try {
    const url = `${env.GEMINI_BASE_URL}/models/${encodeURIComponent(env.GEMINI_MODEL)}:generateContent`;
    const res = await fetch(url, {
      method: "POST",
      headers: {
        "content-type": "application/json",
        "x-goog-api-key": env.GEMINI_API_KEY,
      },
      body: JSON.stringify({
        contents: [
          ...turns.map((t) => ({ role: t.role, parts: [{ text: t.text }] })),
          { role: "user", parts: [{ text: userContent }] },
        ],
        systemInstruction: { parts: [{ text: SYSTEM_PROMPT }] },
        generationConfig: { temperature: 0.3 },
      }),
      signal: AbortSignal.timeout(60_000),
    });
    if (!res.ok) {
      // Provider error details are safe to surface (no request content in them).
      const detail = (await res.text().catch(() => "")).slice(0, 300);
      return { text: FALLBACK_TEXT, degraded: `AI_HTTP_${res.status}:${detail}` };
    }
    const data = (await res.json()) as {
      candidates?: { content?: { parts?: { text?: unknown }[] } }[];
    };
    const parts = data.candidates?.[0]?.content?.parts ?? [];
    const text = parts
      .map((p) => (typeof p.text === "string" ? p.text : ""))
      .join("")
      .trim();
    const shown = text ? presentReply(text) : "";
    return {
      text: shown || "ASTRA could not generate a response.",
      degraded: shown ? null : "AI_EMPTY_RESPONSE",
    };
  } catch (e) {
    return {
      text: FALLBACK_TEXT,
      degraded: `AI_ERROR:${e instanceof Error ? e.name : "unknown"}`,
    };
  }
}
